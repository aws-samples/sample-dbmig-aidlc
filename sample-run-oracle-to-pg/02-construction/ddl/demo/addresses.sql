-- DEMO.ADDRESSES -> demo.addresses
-- NUMBER(19,0) identity -> bigint identity (checks/non-portable-constructs.md: identity needs an integer type)
-- NUMBER(1,0) flag -> smallint + CHECK (0/1 kept, app compares 0/1)
CREATE TABLE demo.addresses (
    id            bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) NOT NULL,
    address_line1 varchar(255),
    address_line2 varchar(255),
    address_type  varchar(255),
    city          varchar(255),
    state         varchar(255),
    postal_code   varchar(255),
    country       varchar(255),
    customer_id   bigint,
    is_default    smallint DEFAULT 0,
    CONSTRAINT addresses_pkey PRIMARY KEY (id),
    CONSTRAINT addresses_is_default_check CHECK (is_default IN (0, 1))
);
-- SYS_C006324 (PK-backing unique index) not re-created: the PRIMARY KEY creates its own.

ALTER TABLE demo.addresses ADD CONSTRAINT fk_addresses_customer
    FOREIGN KEY (customer_id) REFERENCES demo.customers (id);
