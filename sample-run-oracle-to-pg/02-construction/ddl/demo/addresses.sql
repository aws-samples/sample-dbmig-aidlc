CREATE TABLE demo.addresses (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
  address_line1 varchar(255), address_line2 varchar(255), address_type varchar(255),
  city varchar(255), state varchar(255), postal_code varchar(255), country varchar(255),
  customer_id bigint,
  is_default smallint DEFAULT 0 CHECK (is_default IN (0,1))  -- NUMBER(1) flag kept 0/1 (not boolean)
);
-- SYS_C* PK index not re-created (PRIMARY KEY creates its own)
ALTER TABLE demo.addresses ADD CONSTRAINT fk_addresses_customer FOREIGN KEY (customer_id) REFERENCES demo.customers (id);
