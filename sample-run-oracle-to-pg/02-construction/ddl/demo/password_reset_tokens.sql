CREATE TABLE demo.password_reset_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
  token varchar(255), customer_id bigint, expiry_date timestamp(6),
  used smallint DEFAULT 0 CHECK (used IN (0,1))
);
ALTER TABLE demo.password_reset_tokens ADD CONSTRAINT fk_password_reset_customer FOREIGN KEY (customer_id) REFERENCES demo.customers (id);
