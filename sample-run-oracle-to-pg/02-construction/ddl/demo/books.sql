-- DR$BOOKS_TEXT_IDX$* not migrated; SYNC (ON COMMIT) not needed (GIN maintained on write).
CREATE TABLE demo.books (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
  title varchar(255), author varchar(255), isbn varchar(255), description varchar(1000),
  publish_date timestamp(0),          -- Oracle DATE carries time
  year bigint,                         -- NUMBER(10,0)
  created_on timestamp(6), updated_on timestamp(6), created_by varchar(255),
  genre_id bigint, publisher_id bigint, book_type_id bigint,
  search_text varchar(1000)
);
CREATE INDEX idx_books_search ON demo.books (search_text);
CREATE INDEX idx_books_isbn ON demo.books (isbn);
CREATE INDEX idx_books_genre ON demo.books (genre_id);
CREATE INDEX idx_books_publisher ON demo.books (publisher_id);
CREATE INDEX books_text_idx ON demo.books USING gin (to_tsvector('english', coalesce(search_text, '')));
ALTER TABLE demo.books ADD CONSTRAINT fk_books_book_type FOREIGN KEY (book_type_id) REFERENCES demo.book_types (id);
ALTER TABLE demo.books ADD CONSTRAINT fk_books_genre FOREIGN KEY (genre_id) REFERENCES demo.genres (id);
ALTER TABLE demo.books ADD CONSTRAINT fk_books_publisher FOREIGN KEY (publisher_id) REFERENCES demo.publishers (id);
CREATE OR REPLACE FUNCTION demo.trg_book_search_text_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- Oracle '||' treats NULL as '' (and NVL(x,'') is NULL there); PostgreSQL '||' propagates
  -- NULL, so coalesce every operand to keep Oracle's result.
  NEW.search_text := lower(coalesce(NEW.title, '')) || ' ' || lower(coalesce(NEW.author, '')) || ' ' || lower(coalesce(NEW.isbn, ''));
  RETURN NEW;   -- BEFORE ROW trigger must return NEW
END $$;
DROP TRIGGER IF EXISTS trg_book_search_text ON demo.books;
CREATE TRIGGER trg_book_search_text BEFORE INSERT OR UPDATE OF title, author, isbn ON demo.books
  FOR EACH ROW EXECUTE FUNCTION demo.trg_book_search_text_fn();
