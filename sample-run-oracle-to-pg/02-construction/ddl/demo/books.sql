-- DEMO.BOOKS -> demo.books
-- DATE -> timestamp(0) (keeps time of day); NUMBER(10,0) -> bigint.
-- Decision fulltext_redesign (option A, migration-plan.md): CTXSYS.CONTEXT BOOKS_TEXT_IDX
-- -> GIN on to_tsvector('english', coalesce(search_text, '')); DR$ tables not migrated;
-- SYNC (ON COMMIT) dropped (GIN is maintained on write).
CREATE TABLE demo.books (
    id           bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) NOT NULL,
    title        varchar(255),
    author       varchar(255),
    isbn         varchar(255),
    description  varchar(1000),
    publish_date timestamp(0),
    year         bigint,
    created_on   timestamp(6),
    updated_on   timestamp(6),
    created_by   varchar(255),
    genre_id     bigint,
    publisher_id bigint,
    book_type_id bigint,
    search_text  varchar(1000),
    CONSTRAINT books_pkey PRIMARY KEY (id)
);
CREATE INDEX idx_books_search    ON demo.books (search_text);
CREATE INDEX idx_books_isbn      ON demo.books (isbn);
CREATE INDEX idx_books_genre     ON demo.books (genre_id);
CREATE INDEX idx_books_publisher ON demo.books (publisher_id);
CREATE INDEX books_text_idx      ON demo.books USING gin (to_tsvector('english', coalesce(search_text, '')));

ALTER TABLE demo.books ADD CONSTRAINT fk_books_book_type FOREIGN KEY (book_type_id) REFERENCES demo.book_types (id);
ALTER TABLE demo.books ADD CONSTRAINT fk_books_genre     FOREIGN KEY (genre_id)     REFERENCES demo.genres (id);
ALTER TABLE demo.books ADD CONSTRAINT fk_books_publisher FOREIGN KEY (publisher_id) REFERENCES demo.publishers (id);

-- TRG_BOOK_SEARCH_TEXT: keeps search_text populated (part of the data model, so kept).
-- Oracle treats NULL as '' in ||, so each operand is coalesced to reproduce the same string.
CREATE OR REPLACE FUNCTION demo.trg_book_search_text_fn() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.search_text := coalesce(lower(NEW.title), '') || ' ' ||
                       coalesce(lower(NEW.author), '') || ' ' ||
                       coalesce(lower(NEW.isbn), '');
    RETURN NEW;   -- BEFORE ROW trigger: RETURN NEW (NULL would cancel the row)
END;
$$;
DROP TRIGGER IF EXISTS trg_book_search_text ON demo.books;
CREATE TRIGGER trg_book_search_text
    BEFORE INSERT OR UPDATE OF title, author, isbn ON demo.books
    FOR EACH ROW EXECUTE FUNCTION demo.trg_book_search_text_fn();
