CREATE TABLE demo.customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
  username varchar(255), email varchar(255), first_name varchar(255), last_name varchar(255),
  phone_number varchar(255), password_hash varchar(255), sub varchar(255),
  date_of_birth timestamp(0), created_on timestamp(6),
  email_verified smallint DEFAULT 0 CHECK (email_verified IN (0,1)),
  role varchar(255),
  account_expired smallint DEFAULT 0 CHECK (account_expired IN (0,1)),
  credentials_expired smallint DEFAULT 0 CHECK (credentials_expired IN (0,1)),
  account_locked smallint DEFAULT 0 CHECK (account_locked IN (0,1)),
  last_login timestamp(6)
);
