"""Phase gates: blockers, approvals, staleness.

A gate approval stores a fingerprint of the phase's artifacts (sha256 per file plus
the phase's decisions). When a covered file changes later, the gate is *stale*
(computed, never stored) and must be re-approved. Blockers are derived from the
artifacts on disk, like ``dbmig status``.

Approving is a human action. The CLI asks the user to type the phase name on a
terminal; from an agent's shell (no TTY) it requires ``--approved-by`` and
``--via chat`` and the skills only run it after the user said "approved".
"""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List, Optional

from . import config, decisions as dec
from .project import (GATE_QUESTIONS, GATED_PHASES, PHASE_TITLES, VIA, Project,
                      ProjectError, load_yaml, now)

DISCLAIMER_MARK = "AI-GENERATED — VALIDATE BEFORE USE"
SIGNOFF_MARK = "<!-- generated by dbmig gate; edit project.yaml through ./dbmig gate -->"
_SKIP_DIRS = {"review", "__pycache__"}


class GateError(ProjectError):
    pass


# ---- covered files ---------------------------------------------------------

def _walk(d: Path) -> List[Path]:
    if not d.is_dir():
        return []
    out = []
    for p in sorted(d.rglob("*")):
        if p.is_file() and not any(part.startswith(".") or part in _SKIP_DIRS
                                   for part in p.relative_to(d).parts):
            out.append(p)
    return out


def covered_files(ws: Path, phase: str) -> List[Path]:
    a, c, v, o = (ws / "01-assessment", ws / "02-construction",
                  ws / "03-validation", ws / "04-operations")
    if phase == "inception":
        return [f for f in _walk(a)
                if "dms-sc" not in f.relative_to(a).parts[:1]
                and not f.name.startswith("_context")
                and not f.name.startswith(("dms-sc-verification-", "dms-sc-diff-"))]
    if phase == "construction":
        out = sorted(a.glob("dms-sc-diff-*.md")) if a.is_dir() else []
        for f in _walk(c):
            rel = f.relative_to(c)
            top = rel.parts[0]
            if top in ("ddl", "code") or f.name == "conversion-log.md" \
                    or (len(rel.parts) == 1 and (
                        f.name.startswith(("manifest-", "code-manifest-"))
                        or (f.name.startswith("apply_report")
                            and not f.name.startswith("apply_report_postdata")))):
                out.append(f)
        return out
    if phase == "validation":
        out = [f for f in _walk(v) if not f.name.startswith("_context")]
        out += [f for f in _walk(ws / "data") if f.name.startswith("migrate_report")]
        out += sorted(a.glob("dms-sc-verification-*.yaml")) if a.is_dir() else []
        out += sorted(c.glob("apply_report_postdata*.yaml")) if c.is_dir() else []
        return out
    if phase == "operations":
        # identity-reset-<S>.* is regenerated by every reset-identity run, including the
        # --apply at cutover (after this gate): execution output, not part of the plan.
        return [f for f in _walk(o) if not f.name.startswith(("_context", "identity-reset-"))]
    raise GateError(f"not a gated phase: {phase}")


_LIKELY_CAUSE = {
    "inception": "the inventory or DMS SC import was re-run, the migration plan was edited, or a "
                 "decision / questionnaire answer changed",
    "construction": "a converted file was fixed or re-applied (often after a failing equivalence "
                    "test), or units were re-converted",
    "validation": "data was reloaded or compare / run-tests / verify was re-run, so the reports "
                  "were rewritten",
    "operations": "the cutover runbook, rollback plan or monitoring checklist was edited",
}


def _content(f: Path) -> bytes:
    """Manifests also carry later-phase state (post_status from the post-data pass,
    attempts); only (name, status, output_file) count for the construction gate.
    A volatile top-level ``generated_at`` (e.g. ``dms-sc-map-*.json``,
    rewritten by every re-import) does not count either."""
    if f.parent.name == "02-construction" and f.name.startswith(("manifest-", "code-manifest-")):
        m = load_yaml(f) or {}
        return json.dumps([[u.get("name"), u.get("status"), u.get("output_file")]
                           for u in m.get("units") or []]).encode()
    if f.suffix in (".json", ".yaml", ".yml"):
        try:
            d = json.loads(f.read_text()) if f.suffix == ".json" else load_yaml(f)
        except Exception:  # noqa: BLE001 - hash the raw bytes
            d = None
        if isinstance(d, dict) and "generated_at" in d:
            d = {k: v for k, v in d.items() if k != "generated_at"}
            return json.dumps(d, sort_keys=True, default=str).encode()
    return f.read_bytes()


def _decision_state(proj: Project, phase: str) -> Dict[str, str]:
    return {str(d.get("id")): f"{d.get('status')}:{d.get('choice') or ''}"
            for d in proj.decisions if d.get("phase") == phase}


def _policy_state(proj: Project) -> Dict[str, str]:
    return {k: f"{(p or {}).get('choice')}:{(p or {}).get('other') or ''}"
            for k, p in sorted((proj.data.get("policies") or {}).items()) if isinstance(p, dict)}


def fingerprint(proj: Project, phase: str) -> Dict[str, Any]:
    files = {str(f.relative_to(proj.dir)): hashlib.sha256(_content(f)).hexdigest()
             for f in covered_files(proj.dir, phase)}
    decisions = _decision_state(proj, phase)
    ds = "|".join(f"{k}:{v}" for k, v in decisions.items())
    out: Dict[str, Any] = {"algo": "sha256", "files": files, "decisions": decisions}
    if phase == "inception":
        # questionnaire policies shape the plan: changing one after approval is a change
        policies = _policy_state(proj)
        ds += "|" + "|".join(f"{k}:{v}" for k, v in policies.items())
        out["policies"] = policies
    out["digest"] = hashlib.sha256((json.dumps(sorted(files.items())) + ds).encode()).hexdigest()
    return out


def _mtime(ws: Path, rel: str) -> str:
    try:
        import datetime as _dt
        ts = (ws / rel).stat().st_mtime
        return _dt.datetime.fromtimestamp(ts, _dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    except OSError:
        return ""


def _fmt_state(s: str) -> str:
    st, _, choice = (s or "").partition(":")
    return f"{st} ({choice})" if choice else st


def check(proj: Project, phase: str) -> Dict[str, Any]:
    """Compare the approved fingerprint with the current artifacts. Returns ``{"stale": bool, "reasons": [...]}``; each reason
    is ``{"kind", "item", "text"}``."""
    rec = proj.gate(phase).get("fingerprint")
    if not rec:
        return {"stale": False, "reasons": []}
    cur = fingerprint(proj, phase)
    if cur["digest"] == rec.get("digest"):
        return {"stale": False, "reasons": []}
    old = rec.get("files") or {}
    reasons: List[Dict[str, str]] = []
    for f, h in cur["files"].items():
        if f not in old:
            reasons.append({"kind": "file_added", "item": f,
                            "text": f"added {f} (at {_mtime(proj.dir, f)})"})
        elif old[f] != h:
            reasons.append({"kind": "file_changed", "item": f,
                            "text": f"changed {f} (last modified {_mtime(proj.dir, f)})"})
    for f in old:
        if f not in cur["files"]:
            reasons.append({"kind": "file_removed", "item": f, "text": f"removed {f}"})
    for key, kind, label in (("decisions", "decision_changed", "decision"),
                             ("policies", "policy_changed", "questionnaire answer")):
        a, b = rec.get(key) or {}, cur.get(key) or {}
        for k in sorted(set(a) | set(b)):
            if a.get(k) != b.get(k):
                reasons.append({"kind": kind, "item": k,
                                "text": f"{label} {k}: {_fmt_state(a.get(k, 'none'))} -> "
                                        f"{_fmt_state(b.get(k, 'removed'))}"})
    if not reasons:
        reasons.append({"kind": "decisions", "item": "",
                        "text": "a decision or questionnaire answer of this phase changed"})
    return {"stale": True, "reasons": reasons}


def changes_since(proj: Project, phase: str) -> List[str]:
    return [r["text"] for r in check(proj, phase)["reasons"]]


def status(proj: Project, phase: str) -> str:
    g = proj.gate(phase)
    st = str(g.get("status") or "open")
    if st == "approved" and check(proj, phase)["stale"]:
        return "stale"
    return st


def fix_steps(proj: Project, phase: str, reasons: List[Dict[str, str]]) -> List[str]:
    """What to do about a stale gate, as user-facing steps with exact commands."""
    ref = f"--project {proj.dir.name}" if proj.dir.parent.name == "migrations" else f"--dir {proj.dir}"
    steps = [f"Review what changed: the list above, or `./dbmig review {ref} --open` (Gates page; "
             f"the Code and Tests pages show the current files)."]
    steps.append(f"If the change is intended, approve the gate again: "
                 f"`./dbmig gate approve {phase} {ref}` (in chat, say \"approved\" and the "
                 f"assistant records it).")
    if any(r["kind"].startswith("file_") for r in reasons):
        steps.append("If the change was not intended, restore the file(s); the gate turns "
                     "approved again by itself once the content matches what was approved.")
    if any(r["kind"] in ("decision_changed", "policy_changed", "decisions") for r in reasons):
        steps.append("A changed decision or questionnaire answer can also be set back with "
                     f"`./dbmig decision answer` or `./dbmig questionnaire check {ref} --apply`.")
    later = [p for p in GATED_PHASES[GATED_PHASES.index(phase) + 1:]
             if str(proj.gate(p).get("status")) == "approved"]
    if later:
        steps.append(f"Later gates ({', '.join(later)}) keep their approval unless their own "
                     f"files changed, but no further gate can be approved until '{phase}' is "
                     f"re-approved.")
    return steps


# ---- blockers ----------------------------------------------------------------

def _yaml(f: Path) -> Dict[str, Any]:
    try:
        d = load_yaml(f) or {}
        return d if isinstance(d, dict) else {}
    except Exception:  # noqa: BLE001 - unreadable artifact is reported as missing
        return {}


def _units(ws: Path, base: str, schema: str) -> List[Dict[str, Any]]:
    f = config.resolve_manifest(ws / "02-construction", base, schema)
    return list(_yaml(f).get("units") or []) if f.exists() else []


def _skip_decided(proj: Project) -> set:
    return {str(o).upper() for d in dec.list_decisions(proj, status="decided")
            if d.get("kind") == "needs_human" and d.get("choice") == "skip"
            for o in d.get("objects") or []}


def _fmt(names: List[str], n: int = 6) -> str:
    return ", ".join(names[:n]) + (f" … (+{len(names) - n})" if len(names) > n else "")


def _schemas(proj: Project) -> List[str]:
    return [s.upper() for s in proj.schemas]


def blockers(proj: Project, phase: str) -> List[str]:
    ws, out = proj.dir, []
    idx = GATED_PHASES.index(phase)
    for earlier in GATED_PHASES[:idx]:
        st = status(proj, earlier)
        if st == "stale":
            out.append(f"earlier gate '{earlier}' is stale (artifacts changed since approval); "
                       "re-approve it first")
        elif st != "approved":
            out.append(f"earlier gate '{earlier}' is not approved")
    schemas = _schemas(proj)
    dms = proj.entry_path == "dms-sc"
    a = ws / "01-assessment"

    if phase == "inception":
        if not schemas:
            out.append("no schemas in scope (scope.schemas in migration-config.yaml)")
        for s in schemas:
            if dms and not (a / f"dms-sc-map-{s}.json").exists():
                out.append(f"{s}: no DMS SC import (run ./dbmig import-dms-sc)")
            if not dms and not (a / f"inventory-{s}.yaml").exists():
                out.append(f"{s}: no inventory (run ./dbmig inventory --schema {s})")
        if not dms and not (a / "migration-plan.md").exists():
            out.append("no 01-assessment/migration-plan.md")

    elif phase == "construction":
        skipped = _skip_decided(proj)
        for s in schemas:
            tables = _units(ws, "manifest", s)
            code = _units(ws, "code-manifest", s)
            if not dms and proj.strategy_mode != "data_only" and not tables:
                out.append(f"{s}: no table manifest (run ./dbmig convert-schema)")
            for label, units in (("tables", tables), ("code", code)):
                todo, notapplied, human = [], [], []
                for u in units:
                    st = str(u.get("status") or "pending")
                    name = str(u.get("name"))
                    if st in ("pending", "failed"):
                        todo.append(name)
                    elif st == "converted" and not (dms and u.get("origin") == "dms_sc"):
                        notapplied.append(name)
                    elif st == "needs_human" and f"{s}.{name}".upper() not in skipped:
                        human.append(name)
                if todo:
                    out.append(f"{s} {label}: {len(todo)} unit(s) not converted/applied: {_fmt(todo)}")
                if notapplied:
                    out.append(f"{s} {label}: {len(notapplied)} unit(s) converted but not applied: "
                               f"{_fmt(notapplied)}")
                if human:
                    out.append(f"{s} {label}: {len(human)} unit(s) need_human (fix and re-apply, "
                               f"or answer a needs_human decision): {_fmt(human)}")

    elif phase == "validation":
        v = ws / "03-validation"
        for s in schemas:
            if proj.strategy_mode != "schema_only" and not (v / f"reconcile_report-{s}.yaml").exists():
                out.append(f"{s}: no reconcile report (run ./dbmig compare --schema {s})")
            code = [u for u in _units(ws, "code-manifest", s) if u.get("status") == "applied"]
            if code and not (v / f"equivalence-report-{s}.yaml").exists():
                out.append(f"{s}: {len(code)} applied code object(s) but no equivalence report "
                           "(run ./dbmig gen-tests / run-tests)")
            if not dms:
                post = [str(u.get("name")) for u in _units(ws, "manifest", s)
                        if u.get("status") == "applied"
                        and str(u.get("post_status") or "pending") not in ("applied", "skipped")]
                if post:
                    out.append(f"{s}: {len(post)} unit(s) without post-data FKs/triggers applied "
                               f"(run ./dbmig apply-schema --post-data): {_fmt(post)}")
            if dms:
                items = (_yaml(a / f"dms-sc-verification-{s}.yaml").get("items") or {})
                pend = [str(i.get("object")) for i in items.values()
                        if isinstance(i, dict) and str(i.get("status") or "pending") == "pending"]
                if pend:
                    out.append(f"{s}: {len(pend)} VERIFY object(s) not verified: {_fmt(pend)}")

    elif phase == "operations":
        o = ws / "04-operations"
        try:
            cut = (config.load_migration_config().get("cutover") or {})
        except config.ConfigError:
            cut = {}
        need = ["cutover-runbook.md", "monitoring.md"]
        if cut.get("require_rollback_plan", True):
            need.insert(1, "rollback-plan.md")
        for n in need:
            f = o / n
            if not f.exists():
                out.append(f"no 04-operations/{n}")
            elif DISCLAIMER_MARK not in f.read_text(errors="replace")[:1500]:
                out.append(f"04-operations/{n} does not start with the required AI-generated "
                           "disclaimer")

    opened = dec.open_decisions(proj, phase)
    if opened:
        out.append(f"{len(opened)} open decision(s): {', '.join(d['id'] for d in opened)} "
                   "(./dbmig decision list --open)")
    return out


def acknowledgements(proj: Project, phase: str) -> Dict[str, int]:
    """Kinds of open problems the approver must acknowledge explicitly: open
    follow-up items of the phase, plus failures recorded in validation reports."""
    kinds: Counter = Counter()
    fu = _yaml(proj.dir / "follow-up.yaml").get("items") or []
    for i in fu:
        if isinstance(i, dict) and i.get("status") == "open" and i.get("phase") == phase:
            kinds[str(i.get("kind"))] += 1
    if phase == "validation":
        v, a = proj.dir / "03-validation", proj.dir / "01-assessment"
        for s in _schemas(proj):
            rep = _yaml(v / f"equivalence-report-{s}.yaml")
            failed = int((rep.get("summary") or {}).get("failed") or 0)
            if failed and not kinds.get("test_failure"):
                kinds["test_failure"] += failed
            mism = [r for r in (_yaml(v / f"reconcile_report-{s}.yaml").get("results") or [])
                    if isinstance(r, dict) and r.get("status") not in (None, "match")]
            if mism and not kinds.get("data_mismatch"):
                kinds["data_mismatch"] += len(mism)
            items = (_yaml(a / f"dms-sc-verification-{s}.yaml").get("items") or {})
            nf = sum(1 for i in items.values() if isinstance(i, dict) and i.get("status") == "failed")
            if nf:
                kinds["verify_failed"] += nf
    return dict(kinds)


# ---- views -----------------------------------------------------------------

def view(proj: Project, phase: str) -> Dict[str, Any]:
    g = proj.gate(phase)
    st = status(proj, phase)
    out = {
        "phase": phase, "title": PHASE_TITLES[phase], "question": GATE_QUESTIONS[phase],
        "status": st, "by": g.get("by"), "at": g.get("at"), "via": g.get("via"),
        "note": g.get("note"), "acknowledged": g.get("acknowledged") or [],
        "blockers": blockers(proj, phase), "acknowledgements": acknowledgements(proj, phase),
        "history": g.get("history") or [],
    }
    if st == "stale":
        reasons = check(proj, phase)["reasons"]
        out["changes"] = [r["text"] for r in reasons]
        out["reasons"] = reasons
        out["likely_cause"] = _LIKELY_CAUSE[phase]
        out["fix"] = fix_steps(proj, phase, reasons)
    if st == "approved":
        for earlier in GATED_PHASES[:GATED_PHASES.index(phase)]:
            if status(proj, earlier) == "stale":
                out["waits_on"] = earlier
                break
    return out


def next_gate(proj: Project) -> Optional[str]:
    for p in GATED_PHASES:
        if status(proj, p) != "approved":
            return p
    return None


# ---- actions ---------------------------------------------------------------

def approve(proj: Project, phase: str, *, by: str, via: str = "cli",
            note: Optional[str] = None, ack: Optional[List[str]] = None,
            ack_all: bool = False) -> Dict[str, Any]:
    if via not in VIA:
        raise GateError(f"--via must be one of {', '.join(VIA)}")
    if via == "questionnaire":
        raise GateError("gates are never approved by a questionnaire")
    proj.reload()
    b = blockers(proj, phase)
    if b:
        raise GateError("the gate cannot be approved yet:\n  - " + "\n  - ".join(b))
    needed = acknowledgements(proj, phase)
    given = set(ack or [])
    missing = [k for k in needed if not ack_all and k not in given]
    if missing:
        raise GateError("acknowledge these open items first (--ack KIND, or --ack-all):\n  - "
                        + "\n  - ".join(f"{k}: {needed[k]} open" for k in missing))
    acked = [f"{k} ({n})" for k, n in needed.items()]
    g = proj.gate(phase)
    at = now()
    ev = {"status": "approved", "by": by, "at": at, "via": via}
    if note:
        ev["note"] = note
    if acked:
        ev["acknowledged"] = acked
    g.setdefault("history", []).append(ev)
    g.update({"status": "approved", "by": by, "at": at, "via": via, "acknowledged": acked,
              "fingerprint": fingerprint(proj, phase)})
    if note:
        g["note"] = note
    else:
        g.pop("note", None)
    proj.save()
    write_sign_off(proj)
    return view(proj, phase)


def reject(proj: Project, phase: str, *, by: str, reason: str, via: str = "cli") -> Dict[str, Any]:
    if via not in VIA or via == "questionnaire":
        raise GateError("--via must be cli or chat")
    if not (reason or "").strip():
        raise GateError("a rejection needs --reason")
    proj.reload()
    g = proj.gate(phase)
    at = now()
    g.setdefault("history", []).append({"status": "rejected", "by": by, "at": at, "via": via,
                                        "note": reason})
    g.update({"status": "rejected", "by": by, "at": at, "via": via, "note": reason,
              "acknowledged": []})
    g.pop("fingerprint", None)
    proj.save()
    write_sign_off(proj)
    return view(proj, phase)


def _cell(s: Any) -> str:
    return str(s or "").replace("\n", " ").replace("|", "\\|")


def render_sign_off(proj: Project) -> str:
    lines = [SIGNOFF_MARK, f"# Sign-off — {proj.name} ({proj.data.get('pair', '')})", "",
             "Generated from the gate records in `project.yaml`. `by` records who acted; it is "
             "not authentication.", "",
             "| # | Phase | Gate question | Status | By | When | Via | Note |",
             "|---|---|---|---|---|---|---|---|"]
    for i, ph in enumerate(GATED_PHASES, 1):
        g = proj.gate(ph)
        lines.append(f"| {i} | {PHASE_TITLES[ph]} | {GATE_QUESTIONS[ph]} | {status(proj, ph)} | "
                     f"{_cell(g.get('by'))} | {_cell(g.get('at'))} | {_cell(g.get('via'))} | "
                     f"{_cell(g.get('note'))} |")
    done = [d for d in proj.decisions if d.get("status") != "open"]
    if done:
        lines += ["", "## Decisions", "",
                  "| Id | Phase | Kind | Objects | Choice | By | Via | Rationale |",
                  "|---|---|---|---|---|---|---|---|"]
        for d in done:
            lines.append(f"| {d.get('id')} | {d.get('phase')} | {d.get('kind')} | "
                         f"{_cell(', '.join(d.get('objects') or []))} | "
                         f"{_cell(dec.option_label(d) if d.get('status') == 'decided' else d.get('status'))} | "
                         f"{_cell(d.get('by'))} | {_cell(d.get('via'))} | {_cell(d.get('rationale'))} |")
    fu = _yaml(proj.dir / "follow-up.yaml").get("items") or []
    lines += ["", f"Open follow-up items: {sum(1 for i in fu if isinstance(i, dict) and i.get('status') == 'open')}.", ""]
    return "\n".join(lines)


def write_sign_off(proj: Project) -> Optional[Path]:
    """Write SIGN-OFF.md, unless a hand-written one (no generated marker) exists."""
    f = proj.path("SIGN-OFF.md")
    if f.exists() and SIGNOFF_MARK not in f.read_text(errors="replace")[:300]:
        return None
    f.write_text(render_sign_off(proj))
    return f


# ---- enforcement -------------------------------------------------------------

# command -> gate that must be approved before it runs
REQUIRES = {
    "convert-schema": "inception", "convert-code": "inception", "apply-schema": "inception",
    "migrate-data": "construction", "compare": "construction", "gen-tests": "construction",
    "run-tests": "construction", "capture-target-objects": "construction",
    "pre-load-drop": "construction", "post-load-restore": "construction",
    "reset-identity": "operations",
}


def precheck(cmd: str, ws: Path, *, enforce: bool, apply: bool = True) -> Optional[str]:
    """Message when ``cmd`` runs before its prerequisite gate is approved, else None.
    ``reset-identity`` only matters with --apply (``apply``)."""
    phase = REQUIRES.get(cmd)
    if not phase or (cmd == "reset-identity" and not apply):
        return None
    from .project import exists, load
    if not exists(ws):
        return (f"gate '{phase}' has no record yet (no project.yaml); approve it with "
                f"./dbmig gate approve {phase}")
    proj = load(ws, create=False)
    st = status(proj, phase)
    if st == "approved":
        return None
    return f"gate '{phase}' is {st}; '{cmd}' normally runs after it is approved"
