#!/usr/bin/env python3
"""Generate Claude Code skill stubs in .claude/skills/ from the canonical skills/.

Claude Code auto-discovers skills only under .claude/skills/<name>/SKILL.md. The
real skills live in skills/<name>/SKILL.md (shared with Kiro), so each stub copies
just the frontmatter (name + description, which drive discovery) and tells the
assistant to load the canonical file. No symlinks (they break on Windows checkouts
with core.symlinks=false) and no duplicated skill bodies.

Run from anywhere after adding/renaming a skill or editing a description:
    python3 scripts/sync-claude-skills.py          # write stubs
    python3 scripts/sync-claude-skills.py --check  # exit 1 if stubs are stale (CI/tests)
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "skills"
DST = ROOT / ".claude" / "skills"
_FM = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def _stub(name: str, frontmatter: str) -> str:
    return (
        f"---\n{frontmatter}\n---\n\n"
        f"<!-- GENERATED by scripts/sync-claude-skills.py from skills/{name}/SKILL.md "
        "— do not edit here; edit the canonical skill and re-run the script. -->\n\n"
        f"# {name}\n\n"
        f"This is a pointer. **Read `skills/{name}/SKILL.md` (relative to the repository "
        "root) in full now and follow it exactly** — it is the canonical skill, shared with "
        "Kiro. Paths in it (e.g. `references/…`) are relative to "
        f"`skills/{name}/`. Where it says \"Kiro\", read \"you, the AI assistant\"; where it "
        "names another skill (e.g. `db-migration-inception`), invoke that skill.\n"
    )


def expected() -> dict:
    out = {}
    for skill in sorted(SRC.glob("*/SKILL.md")):
        m = _FM.match(skill.read_text())
        if not m:
            raise SystemExit(f"{skill}: missing YAML frontmatter")
        name = skill.parent.name
        out[name] = _stub(name, m.group(1).strip())
    return out


def main(argv) -> int:
    want = expected()
    have = {p.parent.name: p.read_text() for p in DST.glob("*/SKILL.md")} if DST.exists() else {}
    if "--check" in argv:
        stale = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if stale:
            print("stale .claude/skills stubs (run scripts/sync-claude-skills.py): "
                  + ", ".join(stale))
            return 1
        print(f"{len(want)} Claude skill stubs up to date")
        return 0
    for name in set(have) - set(want):          # skill removed/renamed upstream
        shutil.rmtree(DST / name)
    for name, text in want.items():
        (DST / name).mkdir(parents=True, exist_ok=True)
        (DST / name / "SKILL.md").write_text(text)
    print(f"wrote {len(want)} stubs to {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
