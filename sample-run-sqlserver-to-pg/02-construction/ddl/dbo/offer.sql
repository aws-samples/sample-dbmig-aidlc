CREATE EXTENSION IF NOT EXISTS citext SCHEMA dbo;  -- must be on the app's search_path; the type is written dbo.citext because the apply session's search_path does not include dbo
-- case_insensitive_collation decision (option a): columns the application SEARCHES are citext so
-- LIKE keeps SQL Server's _CI_ behaviour (EF .Contains). `=` against a text-typed parameter stays
-- case-sensitive — see the conversion log.
CREATE TABLE dbo.offer (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author dbo.citext NOT NULL, isbn text NOT NULL, bookname dbo.citext NOT NULL, fronturl text,
  genreid integer NOT NULL, conditionid integer NOT NULL, publisherid integer NOT NULL, booktypeid integer NOT NULL,
  summary text, offerstatus integer NOT NULL, comment text, customerid integer NOT NULL,
  bookprice numeric(18,2) NOT NULL,
  createdby text NOT NULL, createdon timestamp(6) NOT NULL, updatedon timestamp(6) NOT NULL
);
CREATE INDEX ix_offer_booktypeid ON dbo.offer (booktypeid);
CREATE INDEX ix_offer_conditionid ON dbo.offer (conditionid);
CREATE INDEX ix_offer_customerid ON dbo.offer (customerid);
CREATE INDEX ix_offer_genreid ON dbo.offer (genreid);
CREATE INDEX ix_offer_publisherid ON dbo.offer (publisherid);
ALTER TABLE dbo.offer ADD CONSTRAINT fk_offer_customer_customerid FOREIGN KEY (customerid) REFERENCES dbo.customer (id);
