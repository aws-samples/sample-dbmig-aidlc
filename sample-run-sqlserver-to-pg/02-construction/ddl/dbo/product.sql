CREATE TABLE dbo.product (
  productid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL, productnumber varchar(25) NOT NULL,
  makeflag boolean NOT NULL DEFAULT true, finishedgoodsflag boolean NOT NULL DEFAULT true,
  color varchar(15), safetystocklevel smallint NOT NULL, reorderpoint smallint NOT NULL,
  standardcost numeric(19,4) NOT NULL, listprice numeric(19,4) NOT NULL,   -- money
  size varchar(5), sizeunitmeasurecode char(3), weightunitmeasurecode char(3), weight numeric(8,2),
  daystomanufacture integer NOT NULL, productline char(2), class char(2), style char(2),
  productsubcategoryid integer, productmodelid integer,
  sellstartdate timestamp(3) NOT NULL, sellenddate timestamp(3), discontinueddate timestamp(3),
  rowguid uuid NOT NULL DEFAULT gen_random_uuid(),
  modifieddate timestamp(3) NOT NULL DEFAULT localtimestamp,
  CONSTRAINT ck_product_daystomanufacture CHECK (daystomanufacture >= 0),
  CONSTRAINT ck_product_listprice CHECK (listprice >= 0.00),
  CONSTRAINT ck_product_reorderpoint CHECK (reorderpoint > 0),
  CONSTRAINT ck_product_safetystocklevel CHECK (safetystocklevel > 0),
  CONSTRAINT ck_product_sellenddate CHECK (sellenddate >= sellstartdate OR sellenddate IS NULL),
  CONSTRAINT ck_product_standardcost CHECK (standardcost >= 0.00),
  CONSTRAINT ck_product_weight CHECK (weight > 0.00)
);
CREATE UNIQUE INDEX ak_product_name ON dbo.product (name);
CREATE UNIQUE INDEX ak_product_productnumber ON dbo.product (productnumber);
CREATE UNIQUE INDEX ak_product_rowguid ON dbo.product (rowguid);
