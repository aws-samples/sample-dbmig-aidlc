CREATE TABLE dbo.databaselog (
  databaselogid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  posttime timestamp(3) NOT NULL, databaseuser varchar(128) NOT NULL, event varchar(128) NOT NULL,
  "schema" varchar(128), "object" varchar(128),   -- awkward identifiers quoted (checklist item 9)
  tsql text NOT NULL, xmlevent xml NOT NULL
);
