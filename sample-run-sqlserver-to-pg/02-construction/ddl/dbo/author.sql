-- CK_Author_BirthDate / CK_Author_HireDate used getdate(): PostgreSQL CHECKs must be IMMUTABLE.
-- Static bounds stay in the CHECK; the dynamic rules (age >= 18, hire date <= tomorrow) move to
-- a BEFORE INSERT/UPDATE trigger (checklist item 1). Behaviour: enforced on write, as before.
CREATE TABLE dbo.author (
  businessentityid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nationalidnumber varchar(15) NOT NULL, loginid varchar(256) NOT NULL,
  organizationnode varchar(50),       -- stored as text path in the source (not hierarchyid)
  jobtitle varchar(50) NOT NULL, birthdate date NOT NULL,
  maritalstatus char(1) NOT NULL, gender char(1) NOT NULL, hiredate date NOT NULL,
  vacationhours smallint NOT NULL DEFAULT 0,
  currentflag boolean NOT NULL DEFAULT true,     -- dbo.Flag (bit)
  modifieddate timestamp(3) NOT NULL DEFAULT localtimestamp,
  CONSTRAINT ck_author_birthdate CHECK (birthdate >= DATE '1930-01-01'),
  CONSTRAINT ck_author_hiredate CHECK (hiredate >= DATE '1996-07-01'),
  CONSTRAINT ck_author_vacationhours CHECK (vacationhours >= -40 AND vacationhours <= 240)
);
CREATE UNIQUE INDEX ak_author_loginid ON dbo.author (loginid);
CREATE UNIQUE INDEX ak_author_nationalidnumber ON dbo.author (nationalidnumber);
CREATE INDEX ix_author_organizationnode ON dbo.author (organizationnode);
CREATE OR REPLACE FUNCTION dbo.trg_author_dynamic_checks_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.birthdate > (current_date - interval '18 years') THEN
    RAISE EXCEPTION 'check constraint "ck_author_birthdate" violated' USING ERRCODE = '23514';
  END IF;
  IF NEW.hiredate > (current_date + 1) THEN
    RAISE EXCEPTION 'check constraint "ck_author_hiredate" violated' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_author_dynamic_checks ON dbo.author;
CREATE TRIGGER trg_author_dynamic_checks BEFORE INSERT OR UPDATE OF birthdate, hiredate ON dbo.author
  FOR EACH ROW EXECUTE FUNCTION dbo.trg_author_dynamic_checks_fn();
