CREATE TABLE dbo.customer (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sub varchar(450) NOT NULL, username text, firstname text, lastname text, email text,
  dateofbirth timestamp(6), phone text,
  createdby text NOT NULL, createdon timestamp(6) NOT NULL, updatedon timestamp(6) NOT NULL
);
CREATE UNIQUE INDEX ix_customer_sub ON dbo.customer (sub);
